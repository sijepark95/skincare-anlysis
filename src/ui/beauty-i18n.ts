export type BeautyTextKey = keyof typeof rows;
export const beautyTextIds = Object.keys(rows) as BeautyTextKey[];
export const beautyLocales = ["en", "ko", "es"] as const;
export function bt(
  locale: BeautyLocale,
  key: BeautyTextKey,
  values: Record<string, string | number> = {},
): string {
  let text: string = rows[key][locale === "ko" ? 1 : locale === "es" ? 2 : 0];
  for (const [name, value] of Object.entries(values))
    text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
export function beautyLabel(locale: BeautyLocale, id: string): string {
  return Object.hasOwn(rows, id) ? bt(locale, id as BeautyTextKey) : id;
}
